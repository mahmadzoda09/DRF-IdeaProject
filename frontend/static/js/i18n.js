const i18n = (() => {
  const detect = () => {
    const nav = (navigator.language || "").slice(0, 2);
    return LANGS[nav] ? nav : "ru";
  };

  let lang;
  try {
    lang = localStorage.getItem("lang");
  } catch {}
  if (!LANGS[lang]) lang = detect();

  return {
    get lang() { return lang; },
    // для таджикского форматы чисел и дат как в ru-RU
    get locale() { return lang === "en" ? "en-US" : "ru-RU"; },
    // названия месяцев и дней недели — по-таджикски, если браузер это умеет
    get dateLocale() {
      return lang === "tg" && Intl.DateTimeFormat.supportedLocalesOf("tg").length ? "tg" : this.locale;
    },
    set(code) {
      if (!LANGS[code]) return;
      lang = code;
      try { localStorage.setItem("lang", code); } catch {}
    },
  };
})();

function t(key, vars = {}) {
  const entry = DICT[key];
  const text = entry ? entry[LANG_ORDER.indexOf(i18n.lang)] ?? entry[0] : key;
  return text.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`));
}

// Статичная разметка: data-i18n="key" (текст), data-i18n-title="key" (подсказка)
function applyStaticI18n(root = document) {
  document.documentElement.lang = i18n.lang;
  document.title = t("app.title");
  root.querySelectorAll("[data-i18n]").forEach((el) => (el.textContent = t(el.dataset.i18n)));
  root.querySelectorAll("[data-i18n-title]").forEach((el) => (el.title = t(el.dataset.i18nTitle)));
  root.querySelectorAll("[data-lang]").forEach((el) => el.classList.toggle("active", el.dataset.lang === i18n.lang));
}
